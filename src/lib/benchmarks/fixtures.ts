/**
 * The benchmark fixture corpus (Phase 71 foundation, expanded in Phase 72).
 *
 * Every fixture is SYNTHETIC, generated in memory by repository-owned
 * builders (pdf-lib test fixture code and the builders below). Nothing is
 * downloaded; no copyrighted or customer documents are used; no personal
 * data exists anywhere in the corpus. Anchor tokens are machine-generated
 * strings (PDFKIT-*) planted so content preservation is objectively
 * measurable — the anchors themselves are the only "content" and are
 * synthetic by construction.
 *
 * Phase 72 rules enforced on this corpus (asserted by test):
 *
 * - Every anchor-shaped token planted in a fixture is listed in
 *   `expected.anchors` — anchor PRECISION would otherwise report honest
 *   engines as fabricating.
 * - Ground truth (pages, anchors, anchor order, tokens, character counts,
 *   table cells, blank pages, unicode/symbol chars, image counts, page
 *   dimensions) always comes from the fixture definition itself, never
 *   from an engine's output.
 * - Provenance is machine-readable: generator, synthetic=true, copyright.
 * - All fixtures stay within the Phase 72 resource bounds
 *   (src/lib/benchmarks/bounds.ts): bounded bytes, bounded pages, no
 *   decompression bombs, no resource-exhausting payloads.
 *
 * Known fixture limitations (documented in the Phase 72 report):
 *
 * - No Tamil-script fixture: pdf-lib's standard-14 fonts are WinAnsi
 *   encoded and cannot encode Tamil; generating a valid Tamil fixture
 *   would require embedding an OFL font file (deferred).
 * - No encrypted/password fixture: pdf-lib cannot author encrypted PDFs
 *   and the repository owns no encrypted sample (production tests mock
 *   the encryption error instead).
 */

