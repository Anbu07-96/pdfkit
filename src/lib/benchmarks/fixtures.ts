/** Aligned table with `rows` rows × `cols` columns of anchor cells. */
async function buildTableGridPdf(
  prefix: string,
  rows: number,
  cols: number,
  options: { splitAfter?: number } = {},
): Promise<Uint8Array> {
  const { PDFDocument, StandardFonts } = await import("pdf-lib");
  const document = await PDFDocument.create();
  const font = await document.embedFont(StandardFonts.Helvetica);
  let page = document.addPage([700, 400]);
  let y = 360;
  for (let r = 1; r <= rows; r += 1) {
    if (options.splitAfter !== undefined && r === options.splitAfter + 1) {
      page = document.addPage([700, 400]);
      y = 360;
    }
    const cells: string[] = [];
    for (let c = 1; c <= cols; c += 1) {
      cells.push(`PDFKIT-${prefix}-R${r}C${c}`);
    }
    page.drawText(cells.join("   "), { x: 20, y, size: 12, font });
    y -= 28;
  }
  return document.save();
}

function tableGrid(
  prefix: string,
  rows: number,
  cols: number,
): { rows: string[][]; anchors: string[] } {
  const tableRows: string[][] = [];
  const anchors: string[] = [];
  for (let r = 1; r <= rows; r += 1) {
    const row: string[] = [];
    for (let c = 1; c <= cols; c += 1) {
      row.push(`PDFKIT-${prefix}-R${r}C${c}`);
    }
    tableRows.push(row);
    anchors.push(...row);
  }
  return { rows: tableRows, anchors };
}

